// Regenerate the portable, single-threaded LibRaw browser asset. No npm install.
const fs = require('node:fs/promises');
const path = require('node:path');
const crypto = require('node:crypto');
const base = 'https://cdn.jsdelivr.net/npm/@colorhythm/libraw-wasm@1.1.1/';
const target = path.resolve(__dirname, '../vendor/libraw');
const cleanText = bytes => bytes.toString().replace(/[\t ]+$/gm, '').trimEnd() + '\n';
async function download(name, sha256) {
  const response = await fetch(base + name);
  if (!response.ok) throw Error(`${name}: HTTP ${response.status}`);
  const bytes = Buffer.from(await response.arrayBuffer());
  if (sha256 && crypto.createHash('sha256').update(bytes).digest('base64') !== sha256) throw Error(`${name}: integrity check failed`);
  return bytes;
}
(async () => {
  const [glue, wasm] = await Promise.all([
    download('dist/libraw.mjs', 'rF5lTgII2DN90x71sVEY8hqeTEsM6W0FjtYyQeiJk0o='),
    download('dist/libraw.wasm', 'xMuXp+Q3LaQaH/bsbhFG843rEltzO4u7LpxScnlTq6g=')
  ]);
  // Only change the ESM delivery wrapper. The LibRaw WASM is unmodified. Its
  // embedded bytes and serialized factory let blob workers run on file:// too.
  const classic = cleanText(glue).replaceAll('import.meta.url', 'globalThis.location.href').replace('export default Module;', '');
  if (classic.includes('export default')) throw Error('Unexpected runtime wrapper');
  await fs.mkdir(target, {recursive: true});
  await fs.writeFile(path.join(target, 'raw-runtime.js'), `// Generated by scripts/build-raw-decoder.cjs. See NOTICE.md and bundled licenses.\n(() => {\n${classic}\nglobalThis.PhotoStudioRawRuntime = {factory: Module, wasm: '${wasm.toString('base64')}'};\n})();\n`);
  for (const [source, name] of [['LICENSE', 'LICENSE.wrapper'], ['LibRaw/COPYRIGHT', 'COPYRIGHT'], ['LibRaw/LICENSE.CDDL', 'LICENSE.CDDL'], ['LibRaw/LICENSE.LGPL', 'LICENSE.LGPL']]) {
    await fs.writeFile(path.join(target, name), cleanText(await download(source)));
  }
  console.log('Built vendor/libraw/raw-runtime.js from verified @colorhythm/libraw-wasm 1.1.1 assets.');
})().catch(error => { console.error(error); process.exitCode = 1; });
